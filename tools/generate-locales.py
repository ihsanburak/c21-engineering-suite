"""Compile compact offline TR translations; English keys remain in original sources."""
from pathlib import Path
import json,re
r=Path(__file__).resolve().parents[1]
catalog=json.loads((r/'locales/tr.json').read_text(encoding='utf-8'))
def fnv(s):
 h=2166136261
 for b in s.encode('utf-8'):h=((h^b)*16777619)&0xffffffff
 return h
seen={}
for en,t in catalog.items():
 assert en and t
 h=fnv(en);assert h not in seen,(en,seen.get(h));seen[h]=(en,t)
 # printf placeholders must retain type/order (no positional formatting).
 assert re.findall(r'%(?:[.0-9]*)(?:[a-zA-Z])',en)==re.findall(r'%(?:[.0-9]*)(?:[a-zA-Z])',t),(en,t)
lines=['/* Generated by tools/generate-locales.py; edit locales/tr.json. */','static const Translation translations[] = {']
for h,(en,t) in sorted(seen.items()):lines.append('{0x%08Xu,%s},'%(h,json.dumps(t,ensure_ascii=False)))
lines+=['};','']
(r/'src/locale_data.h').write_text('\n'.join(lines),encoding='utf-8')
(r/'build/phase3d-catalog-coverage.json').write_text(json.dumps({'translations':len(catalog),'handbook_entries':len(re.findall(r'^ \{"', (r/'src/engine.c').read_text(encoding='utf-8'),re.M)),'handbook_prose_fields':6*len(re.findall(r'^ \{"', (r/'src/engine.c').read_text(encoding='utf-8'),re.M)),'hash_collisions':0},indent=2)+'\n')
print(f'Generated {len(catalog)} translations; hash collisions: 0')

(r/'tests/locale_keys.h').write_text('/* Generated by tools/generate-locales.py; host fixtures only. */\nstatic const char *locale_keys[] = {\n'+''.join(json.dumps(k,ensure_ascii=False)+',\n' for k in catalog)+'};\n',encoding='utf-8')
